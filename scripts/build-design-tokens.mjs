import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
const source = new URL('../website/src/styles/tokens.json', import.meta.url);
export function renderTokens(t) {
  const declarations = (values, prefix = '') => Object.entries(values).map(([key, value]) => `  --${prefix}${key}: ${value};`).join('\n');
  const shared = ['spacing','radius','shadow','font','layout'].map(group => declarations(t[group], `${group}-`)).join('\n');
  let css = `/* Generated by scripts/build-design-tokens.mjs. Edit tokens.json only. */\n:root {\n${shared}\n}\n`;
  for (const [name, colors] of Object.entries(t.themes)) css += `${name === 'light' ? ':root, ' : ''}:root[data-theme="${name}"] {\n  color-scheme: ${name};\n${declarations(colors)}\n}\n`;
  css += `@media (prefers-color-scheme: dark) {\n  :root:not([data-theme]) {\n    color-scheme: dark;\n${declarations(t.themes.dark)}\n  }\n}\n`;
  for (const [name, values] of Object.entries(t.densities)) css += `${name === 'medium' ? ':root, ' : ''}:root[data-density="${name}"] {\n${declarations(values)}\n}\n`;
  for (const [name, size] of Object.entries(t.typography)) css += `${name === 'standard' ? ':root, ' : ''}:root[data-type="${name}"] { font-size: ${size}; }\n`;
  for (const [name, width] of Object.entries(t.breakpoint)) css += `@custom-media --${name} (width < ${width});\n`;
  css += `@media (width < ${t.breakpoint.desktop}) {\n  .site-header { flex-wrap: wrap; }\n  .menu-toggle { margin-left: auto; }\n  .header-panel { flex: 1 0 100%; flex-wrap: wrap; padding-block: var(--spacing-4); }\n  .header-panel nav { flex: 1 0 100%; flex-wrap: wrap; }\n  .header-panel .search { flex: 1 1 16rem; }\n}\n`;
  css += `@media (width < ${t.breakpoint.mobile}) {\n  .shell { width: calc(100% - var(--spacing-8)); }\n  .intro { grid-template-columns: 1fr; gap: var(--spacing-8); }\n  .preview-aside { min-height: 18rem; }\n  .sample-row { grid-template-columns: 1fr; }\n  .route-grid { grid-template-columns: 1fr 1fr; }\n  .site-footer { flex-wrap: wrap; }\n  .preferences { flex-wrap: wrap; }\n}\n`;
  css += `@media (width < ${t.breakpoint.desktop}) { .tool-grid, .skeleton-grid { grid-template-columns: repeat(2, minmax(0, 1fr)); } }\n`;
  css += `@media (width < ${t.breakpoint.mobile}) { .tool-grid, .skeleton-grid { grid-template-columns: minmax(0, 1fr); } }\n`;
  return css;
}
export function generateTokens(check = false) {
  const css = renderTokens(JSON.parse(readFileSync(source, 'utf8')));
  const target = new URL('../website/src/styles/theme.css', import.meta.url);
  if (check) {
    if (readFileSync(target, 'utf8').replaceAll('\r\n','\n') !== css) throw Error('Generated tokens are stale');
  } else writeFileSync(target, css);
  return css;
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  generateTokens(process.argv.includes('--check'));
  console.log('Design tokens: synchronized');
}
