// Browser checks run on actual SSR output; interactive callbacks are exercised by render.rs.
const fs=require('node:fs');
const path=require('node:path');
const assert=require('node:assert/strict');
const {chromium,webkit}=require('playwright');
(async()=>{
 const html=fs.readFileSync(path.resolve('target/ui-4.4.html'),'utf8');
 const results=[];
 for(const [name,engine] of [['chromium',chromium],['webkit',webkit]]){
  const browser=await engine.launch({headless:true});
  try{
   const page=await browser.newPage({viewport:{width:1000,height:950}});
   await page.setContent(html);
   const controls=[page.getByRole('button',{name:'Exécuter',exact:true}),page.getByRole('textbox',{name:'Nom',exact:true}),page.getByRole('textbox',{name:'Notes',exact:true}),page.getByRole('combobox',{name:'Choix',exact:true}),page.getByRole('checkbox',{name:'Accord',exact:true})];
   assert.equal(await controls[2].inputValue(),'Bonjour');
   await controls[0].focus();
   for(let i=1;i<controls.length;i++){await page.keyboard.press('Tab');assert(await controls[i].evaluate(e=>e===document.activeElement),`${name}: tab order ${i}`);}
   await page.keyboard.press('Tab');assert(await page.locator('summary').evaluate(e=>e===document.activeElement));
   await page.keyboard.press('Tab');assert(await page.getByRole('tab',{name:'Premier',exact:true}).evaluate(e=>e===document.activeElement));
   await page.keyboard.press('Tab');assert(await page.getByRole('tabpanel',{name:'Premier',exact:true}).evaluate(e=>e===document.activeElement));
   const ids=await page.locator('[id]').evaluateAll(nodes=>nodes.map(n=>n.id));assert.equal(new Set(ids).size,ids.length);
   const labels=await page.locator('label').evaluateAll(nodes=>nodes.every(n=>n.control!==null));assert(labels);
   assert.equal(await page.locator('script,iframe,img').count(),0);
   await page.addScriptTag({path:require.resolve('axe-core/axe.min.js')});
   const audit=await page.evaluate(async()=>{const r=await axe.run(document,{runOnly:{type:'tag',values:['wcag2a','wcag2aa','wcag21aa']}});return r.violations.map(v=>({id:v.id,impact:v.impact,targets:v.nodes.map(n=>n.target)}))});
   assert.deepEqual(audit,[],`${name}: accessibility`);
   await page.screenshot({path:`docs/evidence/ui-4.4-${name}.png`,fullPage:true});
   await page.setViewportSize({width:360,height:800});
   assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),`${name}: narrow viewport overflow`);
   results.push({browser:name,tab_order:'PASS',labels:'PASS',unique_ids:'PASS',wcag_violations:audit,narrow_viewport:'PASS'});
  }finally{await browser.close();}
 }
 fs.writeFileSync('docs/evidence/ui-4.4-browser.json',JSON.stringify({source:'Dioxus SSR output generated by render.rs; handler tests are native VirtualDom tests',results},null,2)+'\n');
 console.log('Chromium and WebKit: native tab order, labels, unique ids, WCAG audit and narrow viewport PASS');
})().catch(e=>{console.error(e);process.exitCode=1});
